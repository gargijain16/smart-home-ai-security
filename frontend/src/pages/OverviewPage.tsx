import { Area, AreaChart, Bar, BarChart, CartesianGrid, Cell, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts'
import type { ApiError } from '../services/api'
import type { Overview } from '../types/api'
import { SimControls } from '../components/SimControls'
import { Banner, Empty, ErrorState, Panel, Pill, Stat, deviceTone, deviceIcon, severityTone } from '../components/ui'
import { clock, labelColor, labelName, num, pct, timeAgo } from '../services/format'
import type { PageId } from '../components/Shell'

const tip = { background: '#0a1020', border: '1px solid rgba(148,163,184,.25)', borderRadius: 10, fontSize: 12 }

export function OverviewPage({ overview, error, reload, go }: { overview: Overview | null; error: ApiError | null; reload: () => void; go: (p: PageId) => void }) {
  if (error && !overview) return <ErrorState error={error} onRetry={reload} />
  if (!overview) return <p className="p-6 text-sm text-slate-400">Loading overview…</p>
  const o = overview
  const threats = Object.entries(o.threat_distribution).map(([k, v]) => ({ key: k, name: labelName(k), value: v }))
  const m = o.model
  return (
    <>
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <h2 className="text-xl font-extrabold text-white">Security overview</h2>
          <p className="text-sm text-slate-400">Live view of the home’s virtual devices</p>
        </div>
        <SimControls sim={o.simulation} onChange={reload} />
      </div>
      <Banner tone="cyan" title="Simulated data">
        Device events on this page are generated by the built-in simulator and labelled by threshold rules. They are not predictions from the trained model and do not come from real devices.
      </Banner>

      <div className="grid grid-cols-2 gap-3 lg:grid-cols-5">
        <Stat label="Devices monitored" value={o.devices_monitored} hint="virtual devices" />
        <Stat label="Security events" value={num(o.total_events)} hint="stored this session" />
        <Stat label="Suspicious events" value={num(o.suspicious_events)} tone={o.suspicious_events ? 'amber' : 'slate'} hint="flagged by rules" />
        <Stat label="High-priority open" value={num(o.high_priority_open)} tone={o.high_priority_open ? 'red' : 'green'} hint="need review" />
        <Stat label="Model" value={m.available ? (m.is_synthetic ? 'Synthetic' : 'Active') : 'None'} tone={m.available ? (m.is_synthetic ? 'amber' : 'green') : 'slate'}
              hint={m.available ? (m.model_version ?? '') : 'demo mode'} />
      </div>

      <div className="grid gap-4 lg:grid-cols-3">
        <Panel title="Event timeline (15-second buckets)" className="lg:col-span-2">
          {o.timeline.length === 0 ? <Empty title="No events yet">Press Start to begin the simulation.</Empty> : (
            <div className="h-60" role="img" aria-label="Area chart of normal and suspicious events over time">
              <ResponsiveContainer width="100%" height="100%">
                <AreaChart data={o.timeline} margin={{ left: -18, right: 8, top: 8 }}>
                  <CartesianGrid stroke="rgba(148,163,184,.12)" vertical={false} />
                  <XAxis dataKey="t" tick={{ fill: '#94a3b8', fontSize: 11 }} />
                  <YAxis allowDecimals={false} tick={{ fill: '#94a3b8', fontSize: 11 }} />
                  <Tooltip contentStyle={tip} />
                  <Area type="monotone" dataKey="normal" name="Normal" stroke="#34d399" fill="#34d399" fillOpacity={0.15} />
                  <Area type="monotone" dataKey="suspicious" name="Suspicious" stroke="#f87171" fill="#f87171" fillOpacity={0.25} />
                </AreaChart>
              </ResponsiveContainer>
            </div>
          )}
        </Panel>
        <Panel title="Threat distribution">
          {threats.length === 0 ? <Empty title="No threats flagged" /> : (
            <div className="h-60" role="img" aria-label="Bar chart of flagged events by threat type">
              <ResponsiveContainer width="100%" height="100%">
                <BarChart data={threats} layout="vertical" margin={{ left: 20, right: 8 }}>
                  <XAxis type="number" allowDecimals={false} tick={{ fill: '#94a3b8', fontSize: 11 }} />
                  <YAxis type="category" dataKey="name" width={130} tick={{ fill: '#cbd5e1', fontSize: 11 }} />
                  <Tooltip contentStyle={tip} cursor={{ fill: 'rgba(148,163,184,.08)' }} />
                  <Bar dataKey="value" name="Events" radius={[0, 6, 6, 0]}>{threats.map((t) => <Cell key={t.key} fill={labelColor(t.key)} />)}</Bar>
                </BarChart>
              </ResponsiveContainer>
            </div>
          )}
        </Panel>
      </div>

      <div className="grid gap-4 lg:grid-cols-3">
        <Panel title="Device health" action={<button className="text-xs font-semibold text-cyan-300 hover:underline" onClick={() => go('devices')}>Open floor plan</button>}>
          <ul className="space-y-2">
            {o.device_health.map((d) => {
              const Icon = deviceIcon(d.type)
              return (
                <li key={d.id} className="flex items-center justify-between gap-2 rounded-lg border border-slate-700/50 px-3 py-2">
                  <span className="flex min-w-0 items-center gap-2 text-sm"><Icon className="h-4 w-4 shrink-0 text-slate-400" aria-hidden /><span className="truncate">{d.name}</span></span>
                  <Pill tone={deviceTone(d.status)}>{d.status === 'alert' ? `${d.open_alerts} open` : d.status}</Pill>
                </li>
              )
            })}
          </ul>
        </Panel>
        <Panel title="Recent security activity" action={<button className="text-xs font-semibold text-cyan-300 hover:underline" onClick={() => go('events')}>All events</button>}>
          {o.recent_events.length === 0 ? <Empty title="Nothing yet" /> : (
            <ul className="space-y-2">
              {o.recent_events.map((e) => (
                <li key={e.id} className="flex items-center justify-between gap-2 text-sm">
                  <span className="min-w-0"><span className="block truncate text-slate-200">{e.device_name}</span>
                    <span className="text-xs text-slate-500">{clock(e.ts)} · {e.event_type.replace(/_/g, ' ')} · {timeAgo(e.ts)}</span></span>
                  <Pill tone={severityTone(e.severity)}>{e.label === 'normal' ? 'normal' : labelName(e.label)}</Pill>
                </li>
              ))}
            </ul>
          )}
        </Panel>
        <Panel title="Model performance summary" className="border-violet-400/20" action={<button className="text-xs font-semibold text-violet-300 hover:underline" onClick={() => go('evaluation')}>Details</button>}>
          {m.headline ? (
            <>
              {m.is_synthetic && <p className="mb-3 rounded-lg border border-amber-400/30 bg-amber-400/10 p-2 text-xs text-amber-200">Synthetic pipeline check. These numbers are not a benchmark.</p>}
              <dl className="grid grid-cols-2 gap-3 text-sm">
                {([['Accuracy', m.headline.accuracy], ['Macro precision', m.headline.macro_precision], ['Macro recall', m.headline.macro_recall], ['Macro F1', m.headline.macro_f1]] as const).map(([k, v]) => (
                  <div key={k}><dt className="text-xs text-slate-400">{k}</dt><dd className="text-xl font-bold text-violet-200">{pct(v)}</dd></div>
                ))}
              </dl>
              <p className="mt-3 text-xs text-slate-500">Held-out test split · {m.selected_model?.replace('_', ' ')} · {m.model_version}</p>
            </>
          ) : (
            <Empty title="No trained model installed">Train in Colab and copy the artefacts into <code>models/</code>. See the AI intrusion detection page for the steps.</Empty>
          )}
        </Panel>
      </div>
    </>
  )
}
